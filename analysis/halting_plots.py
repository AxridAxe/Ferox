"""Experiment 2 tables and plots: stopping rules for the looped model C on the chain task.

Reads results/halting/C_s*.json (from halting.py) and the A_3x / B_3x eval.json files,
writes results/halting/summary.md and results/plots/halting_*.png. No hand-edited numbers.
"""
import glob
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from halting import TEST_LEVELS, T_MAX  # noqa: E402

OUT = "results/plots"
LEARNED = 0.9  # a seed "learned the task" if its best fixed-T validation accuracy >= this
RULES = ["probe", "fixedpoint", "stable", "probe_safe", "fixedpoint_safe", "stable_safe"]
PLOT_RULES = ["probe", "fixedpoint_safe", "stable_safe"]
STYLE = {  # fixed categorical order (validated reference palette) + distinct markers
    "oracle":     dict(color="#52514e", marker="o", ls=":", label="C oracle T (upper bound)"),
    "fixed8":     dict(color="#2a78d6", marker="s", ls="-", label="C fixed T=8 (training mean)"),
    "fixed32":    dict(color="#6250d6", marker="P", ls="-", label="C fixed T=32"),
    "probe":      dict(color="#eb6834", marker="D", ls="-", label="C + learned halting probe"),
    "fixedpoint": dict(color="#1baf7a", marker="^", ls="-", label="C + fixed-point rule"),
    "stable":     dict(color="#eda100", marker="v", ls="-", label="C + prediction-stability rule"),
    "probe_safe":      dict(color="#eb6834", marker="d", ls="-.", label="C + probe (safe calib.)"),
    "fixedpoint_safe": dict(color="#1baf7a", marker="^", ls="-.", label="C + fixed-point (safe calib.)"),
    "stable_safe":     dict(color="#eda100", marker="v", ls="-.", label="C + stability (safe calib.)"),
    "A":          dict(color="#e87ba4", marker="x", ls="--", label="A (4L), 3x budget"),
    "B":          dict(color="#008300", marker="*", ls="--", label="B scratchpad, 3x budget"),
}
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.color": "#e4e3df", "grid.linewidth": 0.6,
                     "axes.edgecolor": "#8a8984", "lines.linewidth": 2})


def boot_ci(x, n=5000, seed=0):
    x = np.asarray(x, float)
    if len(x) < 2:
        return float(x.mean()), float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    m = rng.choice(x, size=(n, len(x))).mean(1)
    return float(x.mean()), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def load():
    H = [json.load(open(p)) for p in sorted(glob.glob("results/halting/C_s*.json"))]
    base = {}
    for name in ("A_3x", "B_3x"):
        base[name] = []
        for p in sorted(glob.glob(f"results/runs/chain/{name}_s*/eval.json")):
            ev = json.load(open(p))["levels"]
            if all(str(l) in ev for l in TEST_LEVELS):
                base[name].append({l: ev[str(l)]["points"][0] for l in TEST_LEVELS})
    return H, base


def get(h, l, key):
    r = h["levels"][str(l)]
    if key == "oracle":
        return r["oracle"]["acc"], r["oracle"]["flops"]
    if key.startswith("fixed") and key[5:].isdigit():
        f = r["fixed"][key[5:]]
        return f["acc"], f["flops"]
    return r[key]["acc"], r[key]["flops"]


def table(H, base, keys, title):
    lines = [f"\n### {title} (n={len(H)} seeds)\n",
             "Accuracy %: mean [95% bootstrap CI over seeds]; FLOPs = mean inference FLOPs per answer.\n",
             "| method | " + " | ".join(f"{l} hops" for l in TEST_LEVELS) + " |",
             "|---|" + "---|" * len(TEST_LEVELS)]
    for k in keys:
        cells = []
        for l in TEST_LEVELS:
            a = [get(h, l, k)[0] for h in H]
            f = np.mean([get(h, l, k)[1] for h in H])
            m, lo, hi = boot_ci(a)
            ci = f" [{100*lo:.0f}–{100*hi:.0f}]" if not np.isnan(lo) else ""
            cells.append(f"{100*m:.1f}{ci}<br>{f:.1e}")
        lines.append(f"| {STYLE.get(k, {}).get('label', k)} | " + " | ".join(cells) + " |")
    for name, key in (("A_3x", "A"), ("B_3x", "B")):
        rs = base.get(name) or []
        if rs:
            cells = []
            for l in TEST_LEVELS:
                m, lo, hi = boot_ci([r[l]["acc"] for r in rs])
                ci = f" [{100*lo:.0f}–{100*hi:.0f}]" if not np.isnan(lo) else ""
                cells.append(f"{100*m:.1f}{ci}<br>{np.mean([r[l]['flops'] for r in rs]):.1e}")
            lines.append(f"| {STYLE[key]['label']} (n={len(rs)}, all seeds) | " + " | ".join(cells) + " |")
    return lines


def main():
    os.makedirs(OUT, exist_ok=True)
    H, base = load()
    learned = [h for h in H if h["calibration"]["best_fixed_val_acc"] >= LEARNED]
    keys = ["oracle", "fixed8", "fixed16", "fixed32", "fixed64"] + RULES
    L = ["# Experiment 2 — stopping rules for the looped model (generated by analysis/halting_plots.py)\n",
         f"Seeds: {[h['seed'] for h in H]}; learned the task (best fixed-T validation acc ≥ {LEARNED:.0%}): "
         f"{[h['seed'] for h in learned]}. T_max = {T_MAX}. Training levels 1–6 hops; ≥ 8 hops is unseen.\n",
         "\n## Calibrated rule parameters (chosen on in-distribution validation only)\n",
         "| seed | best fixed-T val acc (T) | fixed-point ε (safe) | stability m (safe) | probe τ (safe) | probe training FLOPs |",
         "|---|---|---|---|---|---|"]
    for h in H:
        c = h["calibration"]
        L.append(f"| {h['seed']} | {100*c['best_fixed_val_acc']:.1f} ({c['best_fixed_val_T']}) | "
                 f"{c['chosen']['fixedpoint']['param']:.3g} ({c['chosen']['fixedpoint_safe']['param']:.3g}) | "
                 f"{c['chosen']['stable']['param']} ({c['chosen']['stable_safe']['param']}) | "
                 f"{c['chosen']['probe']['param']} ({c['chosen']['probe_safe']['param']}) | {h['probe']['train_flops']:.2e} |")
    if learned:
        L += table(learned, base, keys, "Seeds that learned the task")
    L += table(H, base, keys, "All seeds")

    # oracle-recovery ratio on unseen levels (learned seeds)
    if learned:
        L += ["\n## Oracle recovery on unseen difficulty (learned seeds)\n",
              "recovery = (rule acc − fixed-T=8 acc) / (oracle acc − fixed-T=8 acc), computed on seed means; "
              "1 = as good as the oracle, 0 = no better than T=8.\n",
              "| rule | " + " | ".join(f"{l} hops" for l in TEST_LEVELS if l >= 8) + " |",
              "|---|" + "---|" * len([l for l in TEST_LEVELS if l >= 8])]
        for k in RULES:
            cells = []
            for l in [l for l in TEST_LEVELS if l >= 8]:
                o = np.mean([get(h, l, "oracle")[0] for h in learned])
                b = np.mean([get(h, l, "fixed8")[0] for h in learned])
                r = np.mean([get(h, l, k)[0] for h in learned])
                cells.append(f"{(r - b) / (o - b):.2f}" if o - b > 0.05 else "n/a (no oracle gain)")
            L.append(f"| {k} | " + " | ".join(cells) + " |")
        L += ["\n## Iterations used vs. difficulty (learned seeds; mean of per-seed mean T, and oracle T)\n",
              "| | " + " | ".join(f"{l}" for l in TEST_LEVELS) + " |", "|---|" + "---|" * len(TEST_LEVELS)]
        L.append("| oracle T | " + " | ".join(f"{np.mean([h['levels'][str(l)]['oracle']['T'] for h in learned]):.1f}" for l in TEST_LEVELS) + " |")
        for k in RULES:
            L.append(f"| {k} mean T | " + " | ".join(f"{np.mean([h['levels'][str(l)][k]['mean_T'] for h in learned]):.1f}" for l in TEST_LEVELS) + " |")
            L.append(f"| {k} % capped at T_max | " + " | ".join(f"{100*np.mean([h['levels'][str(l)][k]['capped'] for h in learned]):.0f}" for l in TEST_LEVELS) + " |")
    if learned:
        L += ["\n## Post-hoc sensitivity (DIAGNOSTIC ONLY — parameters here are read off the test levels, "
              "so these are oracle-tainted, not results)\n",
              "Accuracy % averaged over learned seeds for selected parameter values; mean T in brackets.\n",
              "| rule = param | " + " | ".join(f"{l}" for l in TEST_LEVELS) + " |", "|---|" + "---|" * len(TEST_LEVELS)]
        sens = learned[0]["levels"][str(TEST_LEVELS[0])]["sensitivity"]
        picks = {"fixedpoint": [1e-3, 1e-2, 0.03, 0.1, 0.3], "stable": [2, 4, 8, 12], "probe": [0.5, 0.9, 0.99]}
        for rule, want in picks.items():
            params = [e["param"] for e in sens[rule]]
            for w in want:
                i = int(np.argmin([abs(np.log(p) - np.log(w)) for p in params]))
                cells = []
                for l in TEST_LEVELS:
                    es = [h["levels"][str(l)]["sensitivity"][rule][i] for h in learned]
                    cells.append(f"{100*np.mean([e['acc'] for e in es]):.0f} ({np.mean([e['mean_T'] for e in es]):.0f})")
                L.append(f"| {rule} = {params[i]:.3g} | " + " | ".join(cells) + " |")
    if os.path.exists("results/halting/latency.json"):
        lj = json.load(open("results/halting/latency.json"))
        L += [f"\n## Early-exit wall clock (seed {lj['seed']}, batch 1, 1 thread, fixed-point rule ε={lj['eps']:.3g})\n",
              "| hops | mode | median ms | mean T |", "|---|---|---|---|"]
        L += [f"| {r['level']} | {r['mode']} | {r['median_ms']:.2f} | {r['mean_T']:.1f} |" for r in lj["results"]]
    open("results/halting/summary.md", "w").write("\n".join(L) + "\n")

    # --- plots (learned seeds) -----------------------------------------------------
    S = learned or H
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    ax = axes[0]
    for k in ["oracle", "fixed8", "fixed32"] + PLOT_RULES:
        st = STYLE[k]
        mu = [np.mean([get(h, l, k)[0] for h in S]) for l in TEST_LEVELS]
        ax.plot(TEST_LEVELS, mu, color=st["color"], marker=st["marker"], linestyle=st["ls"], label=st["label"], markersize=6)
    for name, key in (("A_3x", "A"), ("B_3x", "B")):
        if base.get(name):
            st = STYLE[key]
            ax.plot(TEST_LEVELS, [np.mean([r[l]["acc"] for r in base[name]]) for l in TEST_LEVELS],
                    color=st["color"], marker=st["marker"], linestyle=st["ls"], label=st["label"] + " (all seeds)", markersize=6)
    ax.axvline(7, color="#8a8984", linestyle="--", linewidth=1)
    ax.text(7.3, 1.0, "unseen →", fontsize=8, color="#52514e", va="top")
    ax.axhline(0.1, color="#8a8984", linestyle=":", linewidth=1)
    ax.set_xscale("log", base=2); ax.set_xticks(TEST_LEVELS); ax.set_xticklabels(TEST_LEVELS)
    ax.set_xlabel("hops"); ax.set_ylabel("accuracy"); ax.set_ylim(-0.02, 1.02)
    ax.set_title(f"Accuracy vs difficulty (C: {len(S)} learned seeds; mean)")
    ax.legend(fontsize=7, frameon=False, loc="lower left")
    ax = axes[1]
    ax.plot(TEST_LEVELS, [np.mean([h["levels"][str(l)]["oracle"]["T"] for h in S]) for l in TEST_LEVELS],
            color=STYLE["oracle"]["color"], marker="o", linestyle=":", label="oracle T")
    for k in PLOT_RULES:
        st = STYLE[k]
        ax.plot(TEST_LEVELS, [np.mean([h["levels"][str(l)][k]["mean_T"] for h in S]) for l in TEST_LEVELS],
                color=st["color"], marker=st["marker"], label=st["label"])
    ax.plot(TEST_LEVELS, [l + 2 for l in TEST_LEVELS], color="#8a8984", linewidth=1, linestyle="--", label="k + 2 (reference)")
    ax.set_xscale("log", base=2); ax.set_yscale("log", base=2)
    ax.set_xticks(TEST_LEVELS); ax.set_xticklabels(TEST_LEVELS)
    ax.set_xlabel("hops"); ax.set_ylabel("iterations used (mean per example)")
    ax.set_title("Does compute track difficulty?"); ax.legend(fontsize=7, frameon=False)
    fig.tight_layout(); fig.savefig(f"{OUT}/halting_accuracy_and_T.png", dpi=150); plt.close(fig)

    fig, axes = plt.subplots(2, 4, figsize=(14, 6), sharey=True)
    for ax, l in zip(axes.flat, TEST_LEVELS):
        apt = np.mean([h["levels"][str(l)]["acc_per_T"] for h in S], 0)
        f8, f16 = get(S[0], l, "fixed8")[1], get(S[0], l, "fixed16")[1]
        blk = (f16 - f8) / 8  # FLOPs(T) = T * block + head, exactly
        fl = [T * blk + (f8 - 8 * blk) for T in range(1, T_MAX + 1)]
        ax.plot(fl, apt, color="#2a78d6", linewidth=1.5, label="C, fixed T sweep")
        for k in PLOT_RULES:
            st = STYLE[k]
            ax.plot([np.mean([get(h, l, k)[1] for h in S])], [np.mean([get(h, l, k)[0] for h in S])],
                    marker=st["marker"], color=st["color"], linestyle="none", markersize=8, label=st["label"],
                    markeredgecolor="white")
        for name, key in (("A_3x", "A"), ("B_3x", "B")):
            if base.get(name):
                st = STYLE[key]
                ax.plot([np.mean([r[l]["flops"] for r in base[name]])], [np.mean([r[l]["acc"] for r in base[name]])],
                        marker=st["marker"], color=st["color"], linestyle="none", markersize=8, label=st["label"])
        ax.set_xscale("log"); ax.set_title(f"{l} hops" + (" (unseen)" if l >= 8 else ""))
        ax.set_ylim(-0.02, 1.02)
    for ax in axes[-1]:
        ax.set_xlabel("inference FLOPs per answer")
    for ax in axes[:, 0]:
        ax.set_ylabel("accuracy")
    h_, l_ = axes.flat[0].get_legend_handles_labels()
    fig.legend(h_, l_, loc="upper center", ncol=6, fontsize=7, frameon=False)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(f"{OUT}/halting_acc_vs_flops.png", dpi=150); plt.close(fig)
    print(open("results/halting/summary.md").read())


if __name__ == "__main__":
    main()
